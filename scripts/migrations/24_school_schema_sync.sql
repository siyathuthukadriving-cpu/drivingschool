-- app_settings.value is jsonb in the running app
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'app_settings'
      and column_name = 'value' and data_type = 'text'
  ) then
    alter table public.app_settings alter column value drop default;
    alter table public.app_settings alter column value type jsonb using to_jsonb(value);
    alter table public.app_settings alter column value set default '""'::jsonb;
  end if;
end $$;

-- ── Directory of driving schools (uuid ids, richer columns) ──────
-- The earlier script created an integer-keyed version; the app uses this one.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'driving_schools'
      and column_name = 'id' and data_type = 'integer'
  ) then
    drop table public.driving_schools cascade;
  end if;
end $$;

