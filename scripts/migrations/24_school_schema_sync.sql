-- ── Admin overview of access grants ─────────────────────────────
create or replace view public.admin_access_overview as
select ag.user_id,
       u.email,
       ag.expires_at,
       ag.source,
       ag.yoco_checkout_id,
       ag.created_at,
       ag.updated_at,
       case
         when ag.expires_at is null then 'permanent'::text
         when ag.expires_at > now() then 'active'::text
         else 'expired'::text
       end as access_status,
       case
         when ag.expires_at is not null and ag.expires_at > now()
           then extract(day from ag.expires_at - now())::integer
         else 0
       end as days_remaining
from public.access_grants ag
join auth.users u on u.id = ag.user_id
order by ag.updated_at desc;

-- The view joins auth.users; only the service role may read it.
revoke all on public.admin_access_overview from anon, authenticated;
